//! Flash loan pool — lends without collateral inside a single transaction and
//! requires principal + fee back before the call returns.
//!
//! Nothing secures the loan except *atomicity*. The pool transfers the funds
//! out, calls back into the borrower, and then re-reads its own balance. If
//! the borrower did not make the pool whole, the check panics — and that panic
//! unwinds the transfer that funded the loan along with everything the
//! borrower did in between. The pool either ends the call richer by the fee,
//! or the call never happened.
//!
//! Read the security caveats in `README.md` before adapting this. Flash loans
//! are a well-understood attack primitive as much as a useful one, and most of
//! what can go wrong goes wrong in the *contracts around* the pool.
//!
//! Liquidity is owned, not pooled: every deposit mints LP shares to the
//! depositor, and every withdrawal redeems shares at the current share price,
//! so fees earned while a depositor held liquidity accrue to them. The `admin`
//! is only the initial LP and the fee setter.
//!
//! Generated by [soroban-forge](https://github.com/soroban-forge-labs/soroban-forge).

#![no_std]

use soroban_sdk::{
    contract, contractclient, contracterror, contractimpl, contracttype, panic_with_error, token,
    Address, Env, Map,
};

/// Fee ceiling in basis points (10%), enforced at construction.
const MAX_FEE_BPS: u32 = 1_000;

/// One hundred percent, in basis points.
const BPS_DENOMINATOR: i128 = 10_000;

#[contracterror]
#[derive(Copy, Clone, Debug, Eq, PartialEq)]
#[repr(u32)]
pub enum Error {
    /// A supplied amount was zero or negative.
    InvalidAmount = 1,
    /// The configured fee exceeds `MAX_FEE_BPS`.
    InvalidFee = 2,
    /// The pool holds less than the requested amount.
    InsufficientLiquidity = 3,
    /// The borrower did not return principal + fee before its callback ended.
    NotRepaid = 4,
    /// The caller holds no LP shares.
    Unauthorized = 5,
}

#[contracttype]
pub enum DataKey {
    Admin,
    Token,
    FeeBps,
    TotalShares,
    Shares,
}

/// The interface a borrower must expose to receive a flash loan.
///
/// `exec` runs with the borrowed funds already credited to the borrower. By
/// the time it returns, `amount + fee` of `token` must be back in `pool` —
/// transferred there by the borrower — or the whole transaction reverts.
///
/// `exec` is a public entrypoint like any other: anyone can call it directly
/// with arguments of their choosing. A borrower must authenticate its caller
/// rather than trusting the values it is handed (see the README).
#[contractclient(name = "FlashLoanReceiverClient")]
pub trait FlashLoanReceiver {
    fn exec(env: Env, pool: Address, token: Address, amount: i128, fee: i128);
}

#[contract]
pub struct FlashLoanPool;

#[contractimpl]
impl FlashLoanPool {
    /// * `admin` — the initial liquidity provider; the first depositor and the
    ///   address that sets the fee. Anyone may deposit after launch.
    /// * `token` — the SEP-41 token this pool lends
    /// * `fee_bps` — loan fee in basis points (30 = 0.30%), capped at 10%
    pub fn __constructor(env: Env, admin: Address, token: Address, fee_bps: u32) {
        if fee_bps > MAX_FEE_BPS {
            panic_with_error!(&env, Error::InvalidFee);
        }
        env.storage().instance().set(&DataKey::Admin, &admin);
        env.storage().instance().set(&DataKey::Token, &token);
        env.storage().instance().set(&DataKey::FeeBps, &fee_bps);
        env.storage().instance().set(&DataKey::TotalShares, &0i128);
    }

    /// Add liquidity to the pool.
    ///
    /// Anyone may lend to the pool and receive LP shares in return. Shares are
    /// minted at the current share price; the first deposit sets the price at
    /// 1:1. Each depositor can later withdraw their pro-rata slice of the pool,
    /// including their share of fees earned while they held liquidity.
    pub fn deposit(env: Env, from: Address, amount: i128) {
        from.require_auth();
        if amount <= 0 {
            panic_with_error!(&env, Error::InvalidAmount);
        }
        let client = token::Client::new(&env, &Self::token_address(&env));
        let pool = env.current_contract_address();
        client.transfer(&from, &pool, &amount);

        let total_shares: i128 = env.storage().instance().get(&DataKey::TotalShares).unwrap();
        // Balance *before* this deposit moved the tokens in.
        let prev_balance = client.balance(&pool) - amount;

        let shares = if total_shares == 0 || prev_balance == 0 {
            // First deposit, or pool was empty: price is 1:1.
            amount
        } else {
            // Mint proportionally: amount * total_shares / prev_balance.
            // Rounded down — the dust stays in the pool and accrues to the
            // existing LPs who already own it.
            (amount * total_shares) / prev_balance
        };

        if shares == 0 {
            panic_with_error!(&env, Error::InvalidAmount);
        }

        env.storage()
            .instance()
            .set(&DataKey::TotalShares, &(total_shares + shares));

        let mut shares_of: Map<Address, i128> = env
            .storage()
            .instance()
            .get(&DataKey::Shares)
            .unwrap_or(Map::new(&env));
        let existing = shares_of.get(&from).unwrap_or(0);
        shares_of.set(&from, existing + shares);
        env.storage().instance().set(&DataKey::Shares, &shares_of);
    }

    /// Remove liquidity from the pool.
    ///
    /// `to` is both the LP whose shares are redeemed *and* the destination for
    /// the tokens — it must authenticate, and it must hold at least the shares
    /// needed to cover `amount`. Tokens are sent at the current share price;
    /// fees earned since the shares were minted are paid out with them.
    pub fn withdraw(env: Env, to: Address, amount: i128) {
        to.require_auth();
        if amount <= 0 {
            panic_with_error!(&env, Error::InvalidAmount);
        }

        let shares_of: Map<Address, i128> = env
            .storage()
            .instance()
            .get(&DataKey::Shares)
            .unwrap_or(Map::new(&env));
        let shares = shares_of.get(&to).unwrap_or(0);
        if shares == 0 {
            panic_with_error!(&env, Error::Unauthorized);
        }

        let total_shares: i128 = env.storage().instance().get(&DataKey::TotalShares).unwrap();
        let client = token::Client::new(&env, &Self::token_address(&env));
        let pool = env.current_contract_address();
        let pool_balance = client.balance(&pool);

        // Shares needed to produce `amount` tokens, rounded up so we never
        // send more than the LP is entitled to.
        let needed = (amount * total_shares + pool_balance - 1) / pool_balance;
        if needed > shares {
            panic_with_error!(&env, Error::InsufficientLiquidity);
        }

        // Actual tokens sent, rounded down; guaranteed >= amount because the
        // share count was rounded up.
        let tokens = (pool_balance * needed) / total_shares;

        let mut shares_of = shares_of;
        shares_of.set(&to, shares - needed);
        env.storage().instance().set(&DataKey::Shares, &shares_of);
        env.storage()
            .instance()
            .set(&DataKey::TotalShares, &(total_shares - needed));

        client.transfer(&pool, &to, &tokens);
    }

    /// Lend `amount` to `receiver` for the duration of this call.
    ///
    /// The sequence is:
    ///
    /// 1. snapshot the pool's balance,
    /// 2. transfer `amount` to `receiver`,
    /// 3. call `receiver.exec(..)` — the borrower does whatever it likes,
    /// 4. re-read the balance and require it grew by at least `fee`.
    ///
    /// Step 4 is the *only* thing enforcing repayment. There is no collateral
    /// and no credit check: if the balance is short this panics, and the panic
    /// unwinds step 2 along with every state change the borrower made in step
    /// 3. That is what makes an uncollateralized loan safe to offer.
    ///
    /// Anyone may call this, for any `receiver`. A borrower must therefore be
    /// written to expect loans it did not ask for.
    pub fn flash_loan(env: Env, receiver: Address, amount: i128) {
        if amount <= 0 {
            panic_with_error!(&env, Error::InvalidAmount);
        }

        let token_address = Self::token_address(&env);
        let client = token::Client::new(&env, &token_address);
        let pool = env.current_contract_address();

        // Snapshot before anything moves — this is what step 4 compares to.
        let before = client.balance(&pool);
        if before < amount {
            panic_with_error!(&env, Error::InsufficientLiquidity);
        }
        let fee = Self::fee_for(env.clone(), amount);

        // The pool authorizes moving its own funds by virtue of being the
        // caller of the token contract; no signature is involved.
        client.transfer(&pool, &receiver, &amount);

        // Hand control to the borrower. Everything it does from here —
        // including calls back out to other contracts — happens inside this
        // transaction, and unwinds with it if the check below fails.
        FlashLoanReceiverClient::new(&env, &receiver).exec(&pool, &token_address, &amount, &fee);

        if client.balance(&pool) < before + fee {
            panic_with_error!(&env, Error::NotRepaid);
        }
    }

    /// The fee charged on a loan of `amount`.
    ///
    /// Rounded up, so the pool never loses a stroop to truncation: a fee that
    /// rounds to zero would make small loans free.
    pub fn fee_for(env: Env, amount: i128) -> i128 {
        if amount <= 0 {
            panic_with_error!(&env, Error::InvalidAmount);
        }
        let fee_bps: u32 = env.storage().instance().get(&DataKey::FeeBps).unwrap();
        (amount * i128::from(fee_bps) + BPS_DENOMINATOR - 1) / BPS_DENOMINATOR
    }

    /// Liquidity currently available to lend.
    pub fn balance(env: Env) -> i128 {
        let client = token::Client::new(&env, &Self::token_address(&env));
        client.balance(&env.current_contract_address())
    }

    /// The SEP-41 token this pool lends.
    pub fn token(env: Env) -> Address {
        Self::token_address(&env)
    }

    /// The loan fee, in basis points.
    pub fn fee_bps(env: Env) -> u32 {
        env.storage().instance().get(&DataKey::FeeBps).unwrap()
    }

    /// The initial liquidity provider and fee setter.
    pub fn admin(env: Env) -> Address {
        env.storage().instance().get(&DataKey::Admin).unwrap()
    }

    /// LP shares held by `who`, in share units.
    pub fn shares(env: Env, who: Address) -> i128 {
        let shares_of: Map<Address, i128> = env
            .storage()
            .instance()
            .get(&DataKey::Shares)
            .unwrap_or(Map::new(&env));
        shares_of.get(&who).unwrap_or(0)
    }

    /// Total shares outstanding.
    pub fn total_shares(env: Env) -> i128 {
        env.storage().instance().get(&DataKey::TotalShares).unwrap()
    }
}

impl FlashLoanPool {
    fn token_address(env: &Env) -> Address {
        env.storage().instance().get(&DataKey::Token).unwrap()
    }
}

